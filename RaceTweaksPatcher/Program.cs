using Mutagen.Bethesda;
using Mutagen.Bethesda.Synthesis;
using Mutagen.Bethesda.Skyrim;

namespace RaceTweaksPatcher
{
    public class Program
    {
        private static Lazy<PatcherSettings> _settings = null!;

        public static async Task<int> Main(string[] args)
        {
            return await SynthesisPipeline.Instance
                // Synthesis needs an output file to complete the runner step, even for zero changes.
                .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
                .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
                .SetTypicalOpen(GameRelease.SkyrimSE, "RaceTweaksPatcher.esp")
                .Run(args);
        }

        public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            RaceFlagPatcher.Run(_settings.Value, state.LinkCache, state.PatchMod, Console.WriteLine);
        }
    }
}
